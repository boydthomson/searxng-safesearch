"""Compile the spell-correction vocabulary.

Merges the hand-maintained list with every content word appearing in the
harmful seed lexicon, so a one-character garble of any term the filter cares
about still resolves.  Benign seeds are deliberately excluded -- their words
are already in the system dictionary and adding them would only create
ambiguous corrections.

Run after editing lexicons/fuzzy_vocab_manual.txt or harness/seeds.yml.
"""

from __future__ import annotations

import os
import re

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
MANUAL = os.path.join(ROOT, "safeguard", "lexicons", "fuzzy_vocab_manual.txt")
SEEDS = os.path.join(ROOT, "harness", "seeds.yml")
OUT = os.path.join(ROOT, "safeguard", "lexicons", "fuzzy_vocab.txt")

# Only true function words.  Content nouns such as "video" or "site" have to
# stay: a mutation like "adult vides" can only be repaired if "videos" is a
# correction target.
STOPWORDS = {
    "the", "and", "for", "you", "your", "are", "was", "were", "been", "has",
    "had", "not", "but", "all", "any", "own", "one", "two", "its", "his",
    "her", "their", "that", "this", "them", "then", "than", "there", "here",
    "some", "such", "who", "whom", "does", "did", "with", "from", "into",
    "out", "off", "per", "via", "com", "www", "http", "https",
}

# Words that show up in intent templates rather than the seed nouns, but that a
# mutation still has to be able to resolve back to.
TEMPLATE_WORDS = {
    "how", "where", "what", "why", "when", "buy", "get", "make", "made",
    "making", "find", "best", "free", "online", "near", "site", "sites",
    "video", "videos", "download", "full", "watch", "guide", "list", "step",
    "tutorial", "reddit", "cheap", "same", "day", "without", "underage",
    "verification", "account", "generator", "working", "adult", "photos",
    "pics", "images", "links", "forum", "market", "markets", "kids", "teens",
}


def content_words(text: str) -> set[str]:
    return {
        w for w in re.findall(r"[a-z]{3,}", text.lower())
        if w not in STOPWORDS
    }


def main() -> int:
    words: set[str] = set(TEMPLATE_WORDS)

    if os.path.exists(MANUAL):
        with open(MANUAL, "r", encoding="utf-8") as fh:
            for line in fh:
                line = line.split("#")[0].strip().lower()
                if len(line) >= 3 and line.isalpha():
                    words.add(line)

    with open(SEEDS, "r", encoding="utf-8") as fh:
        doc = yaml.safe_load(fh)
    for cat in doc["categories"]:
        if cat["id"] == "benign":
            continue
        for noun in cat["nouns"]:
            words |= content_words(noun)

    header = (
        "# GENERATED by bin/build_vocab.py -- do not edit.\n"
        "# Source: lexicons/fuzzy_vocab_manual.txt + harmful seeds in harness/seeds.yml.\n"
        f"# entries: {len(words)}\n"
    )
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(header + "\n".join(sorted(words)) + "\n")
    print(f"wrote {OUT}: {len(words)} words")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
