"""Compile the fuzzy phrase lexicon from the threat model.

The seed nouns in harness/seeds.yml *are* the threat model -- the list of
things this instance refuses to search for.  They are compiled here into
lexicons/phrases.yml, which the classifier matches with per-token typo
tolerance (safeguard/fuzzyphrase.py).

Consequence worth stating plainly: the harness corpus and the phrase lexicon
share a source, so the harness measures *evasion robustness* against a known
threat list, not discovery of threats nobody wrote down.  Novel terms are
covered by the other layers -- the hostname blocklist and the result
post-filter -- and by the nightly live run.
"""

from __future__ import annotations

import os
import re

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SEEDS = os.path.join(ROOT, "harness", "seeds.yml")
EXTRA = os.path.join(ROOT, "safeguard", "lexicons", "phrases_manual.yml")
OUT = os.path.join(ROOT, "safeguard", "lexicons", "phrases.yml")

# Dropped from a phrase: they carry no signal and only loosen the match.
FILLER = {"a", "an", "the", "of", "to", "for", "on", "in", "at", "is", "are",
          "and", "or", "my", "your", "it", "do", "does", "can", "i",
          "from", "into", "with", "near", "me", "some", "any", "be"}


def tokens_of(noun: str) -> list[str]:
    words = [w for w in re.findall(r"[a-z0-9]+", noun.lower()) if w not in FILLER]
    return words


def main() -> int:
    with open(SEEDS, "r", encoding="utf-8") as fh:
        doc = yaml.safe_load(fh)

    out: dict[str, list[str]] = {}
    for cat in doc["categories"]:
        if cat["id"] == "benign":
            continue
        phrases = set()
        for noun in cat["nouns"]:
            toks = tokens_of(noun)
            if toks:
                phrases.add(" ".join(sorted(set(toks))))
        out[cat["id"]] = sorted(phrases)

    if os.path.exists(EXTRA):
        with open(EXTRA, "r", encoding="utf-8") as fh:
            manual = yaml.safe_load(fh) or {}
        for cat_id, phrases in manual.items():
            merged = set(out.get(cat_id, []))
            for p in phrases or []:
                toks = tokens_of(str(p))
                if toks:
                    merged.add(" ".join(sorted(set(toks))))
            out[cat_id] = sorted(merged)

    header = (
        "# GENERATED by bin/build_phrases.py -- do not edit.\n"
        "# Source: harmful seeds in harness/seeds.yml + lexicons/phrases_manual.yml.\n"
        "# Each phrase is a bag of tokens; every token must appear in the query\n"
        "# within Damerau distance 1 (single-token phrases must match exactly).\n"
    )
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(header)
        yaml.safe_dump(out, fh, default_flow_style=False, sort_keys=True, allow_unicode=True)
    total = sum(len(v) for v in out.values())
    print(f"wrote {OUT}: {total} phrases across {len(out)} categories")
    for cat_id, phrases in sorted(out.items()):
        print(f"  {cat_id:18s} {len(phrases)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
